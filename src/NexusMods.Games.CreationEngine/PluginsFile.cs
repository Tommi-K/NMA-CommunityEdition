using NexusMods.Sdk.FileStore;
using NexusMods.Sdk.Games;
using NexusMods.Sdk.Loadouts;

namespace NexusMods.Games.CreationEngine;

public class PluginsFile : IIntrinsicFile
{
    private readonly ICreationEngineGame _game;
    private readonly ISorter _sorter;
    private readonly ILogger<PluginsFile> _logger;

    private record struct Metadata(RelativePath FileName, ModKey ModKey, Hash Hash, PluginHeader Header);

    public PluginsFile(ILogger<PluginsFile> logger, ICreationEngineGame game, ISorter sorter)
    {
        _game = game;
        _sorter = sorter;
        Path = game.PluginsFile;
        _logger = logger;
    }
    
    public GamePath Path { get; }
    
    public async Task Write(Stream stream, Loadout.ReadOnly loadout, Dictionary<GamePath, SyncNode> syncTree)
    {
        var disabledDlcPlugins = DisabledDlcPlugins(loadout);

        // MakeMetadata returns null when the plugin can't be parsed (usually
        // because the vanilla file isn't backed up yet on a fresh loadout).
        // We drop those entries instead of NRE-ing; they'll be picked up on
        // the next sync once the file store has the archive.
        var plugins = await syncTree
            .Where(p => p.Key.Parent == KnownPaths.Data && _game.PluginExtensions.Contains(p.Key.Extension))
            .Where(p => p.Value.HaveLoadout)
            .Where(p => !disabledDlcPlugins.Contains(p.Key))
            .ToAsyncEnumerable()
            .Select((KeyValuePair<GamePath, SyncNode> plugin, CancellationToken _) => MakeMetadata(plugin))
            .Where(m => m.HasValue)
            .Select(m => m!.Value)
            .ToDictionaryAsync(x => x.ModKey);

        if (plugins.Count == 0)
            return;
        
        var sorted = _sorter.Sort(plugins.Values.ToList(), IdSelector, plugin => RuleCreator(plugin, plugins))
            .ToList();
        _logger.LogDebug("Sorted {Count} plugin files", sorted.Count);
        
        var activeOnly = _game.PluginsFileFormat == PluginsFileFormat.ActiveOnly;

        // The pre-Fallout 4 engines read this file as Windows-1252 and expect CRLF, which
        // matters because the app writes it from Linux, where the default line ending is
        // LF. Latin1 is the built-in encoding that lines up with Windows-1252 across the
        // range plugin names realistically use.
        await using var sw = activeOnly
            ? new StreamWriter(stream, Encoding.Latin1, leaveOpen: true) { NewLine = "\r\n" }
            : new StreamWriter(stream, leaveOpen: true);

        await sw.WriteLineAsync("# Generated by Nexus Mods App");

        foreach (var plugin in sorted)
        {
            // In the asterisk format the file lists every plugin and the prefix marks the
            // active ones; in the older format being listed at all is what activates a
            // plugin, and a prefix would make the name unrecognisable.
            await sw.WriteLineAsync(activeOnly ? plugin.FileName.ToString() : $"*{plugin.FileName}");
        }

        await sw.FlushAsync();
    }

    private static IReadOnlyList<ISortRule<Metadata, ModKey>> RuleCreator(Metadata metadata, Dictionary<ModKey, Metadata> allPlugins)
    {
        var resultList = new List<ISortRule<Metadata, ModKey>>();
        foreach (var master in metadata.Header.Masters)
        {
            // Skip missing masters here, we'll catch that in diagnostics
            if (!allPlugins.ContainsKey(master))
                continue;
            
            resultList.Add(new After<Metadata, ModKey>()
            {
                Other = master,
            });
        }

        // ESLs should come after ESMs
        if (metadata.FileName.Extension == KnownCEExtensions.ESL)
        {
            foreach (var other in allPlugins.Values)
            {
                if (other.FileName.Extension == KnownCEExtensions.ESM)
                    resultList.Add(new After<Metadata, ModKey>()
                    {
                        Other = other.ModKey,
                    });
            }
        }
        
        // ESPs should come after ESMs and ESLs
        if (metadata.FileName.Extension == KnownCEExtensions.ESP)
        {
            foreach (var other in allPlugins.Values)
            {
                if (other.FileName.Extension == KnownCEExtensions.ESM || other.FileName.Extension == KnownCEExtensions.ESL)
                    resultList.Add(new After<Metadata, ModKey>()
                    {
                        Other = other.ModKey,
                    });
            }
        }
        
        return resultList;
    }

    private static ModKey IdSelector(Metadata metadata)
    {
        return metadata.ModKey;
    }

    private static readonly IReadOnlySet<GamePath> NoDisabledPlugins = new HashSet<GamePath>();

    /// <summary>
    /// The plugins of the game's own optional content that the user switched off for this loadout.
    /// </summary>
    /// <remarks>
    /// Those files stay in the game folder - they belong to the installation, and the synchronizer
    /// has no business deleting them. What makes the content load is the plugin being listed here,
    /// so leaving the plugin out is what switches it off. A plugin that other plugins declare as a
    /// master simply becomes a missing master, which the sorter skips and the diagnostics report.
    /// </remarks>
    private IReadOnlySet<GamePath> DisabledDlcPlugins(Loadout.ReadOnly loadout)
    {
        if (_game is not IGameWithDlc gameWithDlc) return NoDisabledPlugins;

        var disabledIds = DisabledGameDlc
            .FindByLoadout(loadout.Db, loadout.Id)
            .Select(static entry => entry.DlcId)
            .ToHashSet(StringComparer.OrdinalIgnoreCase);

        if (disabledIds.Count == 0) return NoDisabledPlugins;

        return gameWithDlc.Dlc
            .Where(dlc => disabledIds.Contains(dlc.Id))
            .Select(static dlc => dlc.Plugin)
            .ToHashSet();
    }

    private async ValueTask<Metadata?> MakeMetadata(KeyValuePair<GamePath, SyncNode> arg)
    {
        var relPath = arg.Key.Path.FileName;
        Hash hash;
        
        // We need to figure out if we should look at the loadout or the disk
        var syncNode = arg.Value;
        if (syncNode.Actions.HasFlag(Actions.ExtractToDisk) || syncNode.Disk.Hash == Hash.Zero || syncNode.SourceItemType == LoadoutSourceItemType.Game)
            hash = syncNode.Loadout.Hash;
        else
            hash = syncNode.Disk.Hash;
        
        var modHeader = await _game.ParsePlugin(hash, relPath);
        if (modHeader is null) return null;
        return new Metadata(relPath, modHeader.Value.ModKey, hash, modHeader.Value);
    }
    


    public Task Ingest(Stream stream, Loadout.ReadOnly loadout, Dictionary<GamePath, SyncNode> syncTree, ITransaction tx)
    {
        // TODO: Implement once we have sorting
        return Task.CompletedTask;
    }
}
