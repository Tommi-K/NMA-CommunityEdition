using System.Text;
using JetBrains.Annotations;

namespace NexusMods.Abstractions.Games;

/// <summary>
/// Reads and writes Mod Organizer 2's <c>modlist.txt</c>: the install order of a profile's mods
/// together with which of them are switched on.
/// </summary>
/// <remarks>
/// The file is stored in reverse priority order - the first line is the mod that loads last and
/// therefore wins file conflicts against everything below it. <see cref="Parse"/> and
/// <see cref="Write"/> both keep that convention, so callers always see the highest priority mod
/// first.
/// </remarks>
[PublicAPI]
public static class ModOrganizerModList
{
    /// <summary>
    /// The name Mod Organizer gives the file.
    /// </summary>
    public const string FileName = "modlist.txt";

    /// <summary>
    /// The comment Mod Organizer puts at the top of the file.
    /// </summary>
    public const string Header = "# This file was automatically generated by Mod Organizer.";

    /// <summary>
    /// The suffix Mod Organizer gives separator entries.
    /// </summary>
    public const string SeparatorSuffix = "_separator";

    /// <summary>
    /// Parses the contents of a <c>modlist.txt</c>, highest priority entry first.
    /// </summary>
    /// <remarks>
    /// Unrecognised lines are skipped rather than reported: the file is hand-editable and a
    /// stray line should not cost the user the rest of their order.
    /// </remarks>
    public static List<ModListEntry> Parse(string contents)
    {
        var entries = new List<ModListEntry>();

        foreach (var rawLine in contents.Split('\n'))
        {
            var line = rawLine.Trim();
            if (line.Length == 0 || line[0] == '#') continue;

            var name = line[1..].Trim();
            if (name.Length == 0) continue;

            switch (line[0])
            {
                case '+':
                    entries.Add(IsSeparatorName(name) ? ModListEntry.Separator(name) : ModListEntry.Mod(name, isEnabled: true));
                    break;
                case '-':
                    entries.Add(IsSeparatorName(name) ? ModListEntry.Separator(name) : ModListEntry.Mod(name, isEnabled: false));
                    break;
                case '*':
                    entries.Add(new ModListEntry(name, IsEnabled: true, ModListEntryKind.Unmanaged));
                    break;
            }
        }

        return entries;
    }

    /// <summary>
    /// Writes the entries as a <c>modlist.txt</c>, expecting the highest priority entry first.
    /// </summary>
    public static string Write(IEnumerable<ModListEntry> entries)
    {
        var sb = new StringBuilder();
        sb.Append(Header).Append('\n');

        foreach (var entry in entries)
        {
            var prefix = entry.Kind switch
            {
                ModListEntryKind.Unmanaged => '*',
                ModListEntryKind.Separator => '+',
                _ => entry.IsEnabled ? '+' : '-',
            };

            sb.Append(prefix).Append(entry.Name).Append('\n');
        }

        return sb.ToString();
    }

    private static bool IsSeparatorName(string name) => name.EndsWith(SeparatorSuffix, StringComparison.OrdinalIgnoreCase);
}
