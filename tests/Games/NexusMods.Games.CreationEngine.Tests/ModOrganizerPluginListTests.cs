using FluentAssertions;
using NexusMods.Abstractions.Games;

namespace NexusMods.Games.CreationEngine.Tests;

/// <summary>
/// The two <c>plugins.txt</c> dialects: New Vegas lists the enabled plugins bare, Skyrim SE and
/// Fallout 4 list every plugin and mark the enabled ones with a <c>*</c>.
/// </summary>
public class ModOrganizerPluginListTests
{
    [Fact]
    public void ParseReturnsTheNamesOfBothDialects()
    {
        const string asterisk = "# comment\n*Enabled.esp\nDisabled.esp\n";
        const string activeOnly = "# comment\r\nFirst.esp\r\nSecond.esp\r\n";

        ModOrganizerPluginList.Parse(asterisk).Should().Equal("Enabled.esp", "Disabled.esp");
        ModOrganizerPluginList.Parse(activeOnly).Should().Equal("First.esp", "Second.esp");
    }

    /// <summary>
    /// In the asterisk dialect a bare name is a disabled plugin, so writing the names alone would
    /// switch every plugin off.
    /// </summary>
    [Fact]
    public void AnAsteriskFileKeepsItsMarksThroughParseEntriesAndWrite()
    {
        const string generated = "# Generated by Nexus Mods App\n*Unofficial Patch.esp\n*SomeMod.esp\nDisabled.esp\n";

        var written = ModOrganizerPluginList.Write(ModOrganizerPluginList.ParseEntries(generated));

        written.Should().Be($"{ModOrganizerPluginList.Header}\n*Unofficial Patch.esp\n*SomeMod.esp\nDisabled.esp\n");
    }

    [Fact]
    public void AnActiveOnlyFileStaysBareThroughParseEntriesAndWrite()
    {
        const string generated = "# Generated by Nexus Mods App\r\nFalloutNV.esm\r\nSomeMod.esp\r\n";

        var written = ModOrganizerPluginList.Write(ModOrganizerPluginList.ParseEntries(generated));

        written.Should().Be($"{ModOrganizerPluginList.Header}\nFalloutNV.esm\nSomeMod.esp\n");
    }
}
